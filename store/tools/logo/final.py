"""Builds Stemma's icon files from the "asterisk bloom" design.

Outputs:
  store/icon-512.png                               Play Store icon (full bleed; Play rounds the corners)
  app/src/main/res/mipmap-*/ic_launcher_foreground.png  adaptive icon foreground (petals, letters, bead)
  app/src/main/res/mipmap-*/ic_launcher_background.png  adaptive icon background (night sky)
  app/src/main/res/drawable/ic_launcher_monochrome.xml  single-colour icon for Android 13+ themed icons
  app/src/main/res/drawable-nodpi/stemma_mark.png       the bloom on its own, for the Explore and About screens

usage: python3 store/tools/logo/final.py <chrome-binary>
"""
import asyncio
import math
import pathlib
import sys

from PIL import Image
from playwright.async_api import async_playwright

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import concepts  # noqa: E402
from concepts import C, W, petal  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[3]
RES = ROOT / "app/src/main/res"

# Adaptive icons: the layer is 108dp, the launcher shows the middle 72dp, and anything outside a
# 66dp circle may be cut off. The bloom is 808 of 1024 units across, so it is scaled to fit that circle.
ADAPTIVE_SCALE = 0.74
DENSITIES = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}


def split(svg):
    """Separates the concept-B SVG into its background and its bloom (everything else)."""
    head, rest = svg.split("</defs>", 1)
    body = rest.rsplit("</svg>", 1)[0]
    bg_end = body.index("<g transform=\"rotate(")
    return head + "</defs>", body[:bg_end], body[bg_end:]


def foreground_svg(scale):
    head, _, bloom = split(concepts.concept_b())
    return f'{head}<g transform="translate({C} {C}) scale({scale}) translate({-C} {-C})">{bloom}</g></svg>'


def background_svg():
    head, background, _ = split(concepts.concept_b())
    return f"{head}{background}</svg>"


def full_svg(scale=0.94):
    head, background, bloom = split(concepts.concept_b())
    return f'{head}{background}<g transform="translate({C} {C}) scale({scale}) translate({-C} {-C})">{bloom}</g></svg>'


def monochrome_xml():
    """Petals and bead as one plain silhouette. Themed icons are drawn in a single colour."""
    length, tip_r, neck = 300, 104, 70
    groups = []
    for i in range(6):
        groups.append(f'''    <group android:rotation="{i * 60}" android:pivotX="{C}" android:pivotY="{C}">
        <path android:fillColor="#FFFFFFFF" android:pathData="{petal(C, C, length, tip_r, neck)}" />
    </group>''')
    bead = f"M {C} {C - 92} A 92 92 0 1 1 {C - 0.1} {C - 92} Z"
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by store/tools/logo/final.py. Single-colour icon for Android 13+ themed icons. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="{W}"
    android:viewportHeight="{W}">
  <group android:pivotX="{C}" android:pivotY="{C}" android:scaleX="{ADAPTIVE_SCALE}" android:scaleY="{ADAPTIVE_SCALE}">
{chr(10).join(groups)}
    <path android:fillColor="#FFFFFFFF" android:pathData="{bead}" />
  </group>
</vector>
'''


async def render(chrome, jobs):
    async with async_playwright() as p:
        browser = await p.chromium.launch(executable_path=chrome, args=["--no-sandbox"])
        page = await browser.new_page(viewport={"width": W, "height": W})
        for svg, out, transparent in jobs:
            bg = "transparent" if transparent else "#000"
            await page.set_content(f'<html><body style="margin:0;background:{bg}">{svg}</body></html>')
            await page.screenshot(path=str(out), clip={"x": 0, "y": 0, "width": W, "height": W}, omit_background=transparent)
        await browser.close()


def main():
    chrome = sys.argv[1]
    work = ROOT / "store/tools/logo/build"
    work.mkdir(exist_ok=True)
    jobs = [
        (full_svg(), work / "full.png", False),
        (foreground_svg(ADAPTIVE_SCALE), work / "foreground.png", True),
        (background_svg(), work / "background.png", False),
        (foreground_svg(1.0), work / "mark.png", True),
    ]
    for svg, out, _ in jobs:
        out.with_suffix(".svg").write_text(svg)
    asyncio.run(render(chrome, jobs))

    Image.open(work / "full.png").convert("RGBA").resize((512, 512), Image.LANCZOS).save(ROOT / "store/icon-512.png")
    for density, px in DENSITIES.items():
        d = RES / f"mipmap-{density}"
        d.mkdir(parents=True, exist_ok=True)
        Image.open(work / "foreground.png").resize((px, px), Image.LANCZOS).save(d / "ic_launcher_foreground.png")
        Image.open(work / "background.png").convert("RGB").resize((px, px), Image.LANCZOS).save(d / "ic_launcher_background.png")
    nodpi = RES / "drawable-nodpi"
    nodpi.mkdir(exist_ok=True)
    # Cropped to the bloom itself (808 of 1024 units), 288 px across.
    mark = Image.open(work / "mark.png")
    inset = (W - 820) // 2
    mark.crop((inset, inset, W - inset, W - inset)).resize((288, 288), Image.LANCZOS).save(nodpi / "stemma_mark.png")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(monochrome_xml())
    print("icons written")


if __name__ == "__main__":
    main()
